    review=[]
    for q in cases:
        if q["kind"]=="shared_TP":continue
        code=q["code"]
        if q["kind"]=="miss":
            q.update(visual_note=MISSES[code],visual_group="Small 检出、融合漏检的同类 GT",annotation_relation="开发 GT 已标为 class0")
        else:
            n=code[1:]
            overlap=q["nearest_gt_iou"]
            if overlap<.1:relation="无邻近标注"
            elif overlap<.5:relation="范围不合"
            elif q["nearest_gt_class"]!=q["cls"]:relation="异类框匹配"
            else:relation="重复框"
            q.update(visual_note=NOTES[n],visual_group=group[n],annotation_relation=relation)
        review.append(q)
    fp=[q for q in review if q["kind"]=="shared_FP"]
    counts=Counter(q["annotation_relation"] for q in fp)
    visual=Counter(q["visual_group"] for q in fp)
