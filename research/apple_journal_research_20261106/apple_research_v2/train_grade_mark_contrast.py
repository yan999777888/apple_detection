def audited_marks():
    manifest=io.read(io.MANIFEST)["samples"]
    local={r["path"]:r for r in io.read(MARKS)["samples"]}
    if not set(local)<=set(r["path"] for r in manifest if r["split"]=="train"):
        raise ValueError("Only training annotations allowed")
    photos,masks,meta=shared.dataset(True,local,SUPPORT)
    # Woo scratch polygons identify damage. Autogenerated zeros outside them do not certify normal skin.
    for i,r in enumerate(meta):
        if r["domain"]=="woo":masks[i][masks[i]!=1]=-1
    rows={r["path"]:r for r in io.read(SUPPORT)["samples"] if r["source"]=="PSU_training_dates" and r["split"]=="train"}
    with ZipFile(penn.ARCHIVE) as z:
        ann=json.loads(z.read("train/_annotations.coco.json"))
    ids={a["id"]:a for a in ann["annotations"]}
    for i,r in enumerate(meta):
        if r["key"] in rows:
            source=rows[r["key"]]
            poly=[p for a in source["original_lesions"] for p in ids[a["id"]]["segmentation"]]
            pos=shared.map_region(poly,source["source_box"])
            masks[i][pos>0]=1
            meta[i]=dict(r,domain="penn")
    active=np.flatnonzero(np.any(masks>=0,axis=(1,2)))
    return [photos[i] for i in active],masks[active],[meta[i] for i in active],local


def pooled_within(logits,labels,which,maximum):
    usable=labels.eq(which).flatten(1)
    values=logits.flatten(1).masked_fill(~usable,-1e4).topk(maximum,dim=1).values
    keep=values>-1e3
    pooled=(values*keep).sum(1)/keep.sum(1).clamp_min(1)
    return pooled,usable.any(1)


def rank(tables):
    a,w=np.array(tables["auto"]),np.array(tables["whole"])
    checks=(a[0,0]>=20,a[2,2]>=17,a[2,0]==0,w[0,0]>=23,w[2,0]==0,
            w[2,2]>=16,a[1,1]>3)
    # Parents from both historical comparisons were frozen before this fit.
    return tuple(map(int,(all(checks),sum(checks[:-1]),a[1,1],a[0,0],w[1,1],w[0,0])))


def collect(model,photos):
    # Training the mark head does not change the underlying local features.
    pairs=[]
    with torch.no_grad():
        for j in range(0,len(photos),20):
            f,z=model.encode(grade.tensor_rgb(photos[j:j+20],"cuda"))
            pairs.append((f.half(),z))
    return torch.cat([f for f,z in pairs]),torch.cat([z for f,z in pairs])


def work():
    if (OUT/"selection.json").is_file():raise ValueError("Completed trial already exists")
    torch.manual_seed(SEED);cv2.setNumThreads(1);torch.set_num_threads(2)
    torch.backends.cudnn.deterministic=True;torch.backends.cudnn.benchmark=False
    rng=np.random.default_rng(SEED)
    ancestor,cut,side=load(PARENT,"cuda")
    if (cut,side)!=(1.0,224):raise ValueError("Requires original deployed unit")
    model=MarkContrastGrade().cuda();model.parent.load_state_dict(ancestor.state_dict())
    model.parent.eval().requires_grad_(False)
    pics,labels,meta,marks=audited_marks()
    counts=Counter()
    for row,mask in zip(meta,labels,strict=True):
        counts[row["domain"],bool(np.any(mask==1)),bool(np.any(mask==0))]+=1
    protocol=dict(architecture=ARCH,parent=grade.file_sha(PARENT/"weights.pt"),anno=grade.file_sha(MARKS),
                  guard=grade.file_sha(SUPPORT),woo=grade.file_sha(shared.WOO),psu=grade.file_sha(penn.ARCHIVE),
                  scopes=[dict(domain=k[0],confirmed_damage=k[1],confirmed_normal=k[2],views=n) for k,n in sorted(counts.items())],
                  positives="AF train human-readable boxes, original Woo scratch polygons, original eligible PSU lesion polygons. Only positives in the latter two datasets.",
                  negatives="Explicit AF normal-structure boxes only; stem/calyx/skin/specular texture. Unknown locations receive no negative targets. Same-face positive/normal region ranking where both are available.",
                  grade="Frozen border parent severe decision. For all other fruit, top three smoothed local heat responses alone decide good vs mild. No photo-grade CE, no whole-image pooled context or previous good/mild scores.",
                  gate="development auto good>=20/25, severe correct>=17/17, severe->good=0, mild>3/15; whole good>=23/25, severe->good=0, severe correct>=16/17. Maximize mild then good among passing checkpoints",
                  seed=SEED,updates=400,code=grade.file_sha(__file__),network=grade.file_sha(Path(__file__).with_name("grade_mark_contrast.py")),
                  exposure="Each step 8 AF positive, 6 Woo positive, 4 PSU positive, 12 AF confirmed normal. Uniform by source image within source/bucket. Local positions or paired ranks only. Multi-view AF crops share an original key.")
    io.atomic(OUT/"protocol.json",protocol)
    x,z=collect(model,pics);y=torch.tensor(labels,device="cuda")
    p,m,vm=shared.dataset(False,{},SUPPORT);vx,vz=collect(model,p)
    stock,_=shared.evaluate(vz.argmax(1).cpu().numpy(),vm)
    bank=defaultdict(lambda:defaultdict(list))
    for i,r in enumerate(meta):
        if (labels[i]==1).any():bank[r["domain"],1][r["key"]].append(i)
        if (labels[i]==0).any():bank[r["domain"],0][r["key"]].append(i)
    groups={k:list(v.values()) for k,v in bank.items()}
    opt=torch.optim.AdamW(model.mark.parameters(),lr=.0015,weight_decay=.025)
    hist=[];winner=None
    for t in range(1,401):
        batch=[]
        for key,size in ((("af",1),8),(("woo",1),6),(("penn",1),4),(("af",0),12)):
            choices=groups[key]
            for _ in range(size):
                choices_i=choices[rng.integers(len(choices))]
                batch.append(choices_i[rng.integers(len(choices_i))])
        f=x[batch].float();lab=y[batch]
        if rng.random()<.5:f=f.flip([-1]);lab=lab.flip([-1])
        logits,_=model.evidence(f)
        pos,hasp=pooled_within(logits,lab,1,3)
        neg,hasn=pooled_within(logits,lab,0,4)
        paired=hasp&hasn
        # Positive boxes are coarse; top local responses can explain a small mark inside a box.
        loss=F.softplus(-pos[hasp]).mean()+2.8*F.softplus(neg[hasn]).mean()
        loss=loss+.9*F.softplus(1.4-(pos[paired]-neg[paired])).mean() if bool(paired.any()) else loss
        loss=loss+.25*F.softplus(.8-pos[hasp,None]+neg[None,hasn]).mean()
        opt.zero_grad(set_to_none=True);loss.backward()
        torch.nn.utils.clip_grad_norm_(model.mark.parameters(),3,error_if_nonfinite=True);opt.step()
        if t%10:continue
        with torch.inference_mode():
            pred=[]
            for j in range(0,len(vm),24):
                _,e=model.evidence(vx[j:j+24].float())
                pred+=model.combine(vz[j:j+24],e).argmax(1).cpu().tolist()
        tables,_=shared.evaluate(pred,vm);r=rank(tables)
        h=dict(step=t,metrics=tables,rank=r);hist.append(h)
        if winner is None or r>winner:
            winner=r;chosen=h;io.atomic(OUT/"weights.pt",model.state_dict(),tensor=True)
        if t%50==0:print(t,tables["auto"],"best",chosen["step"],flush=True)
    io.atomic(OUT/"history.json",hist)
    receipt=dict(architecture=ARCH,input_side=224,threshold=1.,weights_sha256=grade.file_sha(OUT/"weights.pt"),
                 step=chosen["step"],passed=bool(winner[0]),metrics=chosen["metrics"],parent_validation=stock,
                 protocol_sha256=grade.file_sha(OUT/"protocol.json"))
    io.atomic(OUT/"selection.json",receipt)
    # Verify the deployed registry returns the same three grades as the cached selection model.
    restored,cut,side=load(OUT,"cuda")
    with torch.no_grad():
        direct=restored(grade.tensor_rgb(p[:8],"cuda")).argmax(1)
        f,s=collect(restored,p[:8]);_,xx=restored.evidence(f.float())
        equivalent=bool(direct.eq(restored.combine(s,xx).argmax(1)).all())
    if not equivalent:raise ValueError("Deployed branch disagrees with development outputs")
    print(receipt,flush=True)


if __name__=="__main__":work()

